import pandas as pd
import numpy as np
import os
import tempfile
import soundfile as sf
import numpy as np
from pathlib import Path

from eval.model_wrapper import ASRModelWrapper
from eval.metrics import calculate_wer, calculate_accuracy

# Optional: test OpenAI Answer Generator (used later in RAG pipelines)
try:
    from backend.app.answer_generator import OpenAIAnswerGenerator
except Exception:
    OpenAIAnswerGenerator = None


def _test_groq_endpoint() -> bool:
    """Create a short silent WAV and verify the Groq Whisper endpoint works.
    Returns True on success, False on failure.
    """
    sr = 16000
    silence = np.zeros(int(0.5 * sr), dtype=np.float32)
    fd, tmp_path = tempfile.mkstemp(suffix=".wav")
    os.close(fd)
    sf.write(tmp_path, silence, sr)
    try:
        wrapper = ASRModelWrapper()
        _ = wrapper.transcribe(tmp_path)  # Should succeed (may return empty string)
        return True
    except Exception as e:
        print(f"Groq endpoint test failed: {e}")
        return False
    finally:
        try:
            os.remove(tmp_path)
        except OSError:
            pass


def _test_openai_endpoint() -> bool:
    """Send a trivial prompt to the OpenAI answer generator to verify the key.
    Returns True on success, False on failure.
    """
    if OpenAIAnswerGenerator is None:
        return True  # No generator available – skip the test
    try:
        gen = OpenAIAnswerGenerator()
        _ = gen.generate("What is 2+2?", [])
        return True
    except Exception as e:
        print(f"OpenAI endpoint test failed: {e}")
        return False


def run_benchmark(
    manifest_path: str = "eval/manifests/eval_harness_manifest.csv",
    model_path: str = "models/asr_model.pt",  # retained for compatibility, not used by Groq wrapper
    output_report: str = "eval/reports/benchmark_results.csv",
) -> None:
    """Run the benchmark after confirming API endpoints are reachable.

    * Loads the manifest generated by the harness.
    * Verifies Groq Whisper and (optionally) OpenAI endpoints.
    * Transcribes each noisy sample via Groq, computes WER / accuracy.
    * Writes detailed and summary CSV reports.
    """
    # Prepare report path
    report_path = Path(output_report)
    report_path.parent.mkdir(parents=True, exist_ok=True)

    # 1️⃣ Verify external APIs
    print("\n=== Testing API endpoints ===")
    if not _test_groq_endpoint():
        print("❌ Groq API test failed – aborting benchmark.")
        return
    if not _test_openai_endpoint():
        print("❌ OpenAI API test failed – aborting benchmark.")
        return
    print("✅ All endpoints reachable. Starting benchmark...\n")

    # 2️⃣ Initialize the ASR wrapper (Groq)
    model_wrapper = ASRModelWrapper(model_path)

    # 3️⃣ Load the manifest produced by the harness
    print(f"Loading evaluation manifest from {manifest_path}...")
    df = pd.read_csv(manifest_path)
    if df.empty:
        print("Manifest is empty. No samples to evaluate.")
        return

    results = []
    total = len(df)
    print(f"Starting benchmark on {total} samples...")
    for idx, row in df.iterrows():
        noisy_path = row["noisy_path"]
        reference_text = row["text"]
        # Guard against missing/NaN references
        if pd.isna(reference_text):
            reference_text = ""
        else:
            reference_text = str(reference_text)

        env = row["environment"]
        snr = row["snr"]
        dataset = row["set"]

        # 4️⃣ Transcribe via Groq (chunking handled inside ASRModelWrapper)
        try:
            hypothesis = model_wrapper.transcribe(noisy_path)
        except Exception as e:
            print(f"Error transcribing {noisy_path}: {e}")
            hypothesis = ""

        # 5️⃣ Compute metrics
        wer = calculate_wer(reference_text, hypothesis)
        acc = calculate_accuracy(reference_text, hypothesis)

        results.append({
            "sample_id": idx,
            "set": dataset,
            "environment": env,
            "snr": snr,
            "reference": reference_text,
            "hypothesis": hypothesis,
            "wer": wer,
            "accuracy": acc,
        })

        if (idx + 1) % 10 == 0:
            print(f"Processed {idx + 1}/{total} samples...")

    # 6️⃣ Save detailed CSV
    results_df = pd.DataFrame(results)
    results_df.to_csv(output_report, index=False)

    # 7️⃣ Summary report
    print("\n--- Benchmark Summary ---")
    summary = results_df.groupby(["set", "environment", "snr"])[["wer", "accuracy"]].mean().reset_index()
    print(summary.to_string(index=False))
    summary_path = report_path.with_name("summary_report.csv")
    summary.to_csv(summary_path, index=False)

    print(f"\nDetailed report saved to: {output_report}")
    print(f"Summary report saved to: {summary_path}")


if __name__ == "__main__":
    # Run the benchmark (model_path is unused for Groq but kept for API compatibility)
    run_benchmark()
